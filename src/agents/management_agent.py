"""
Management Negotiator Agent (Corporate Executive & HR/Legal Defense).
Represents Taiwan Micron Management and US Corporate Guidelines.
"""

from typing import Dict, Any
from src.agents.base_agent import BaseAgent


class ManagementAgent(BaseAgent):
    def __init__(self):
        system_prompt = (
            "你是台灣美光科技（Micron Taiwan）的資方首席談判代表兼人資副總。"
            "你的目標是嚴格守護跨國母公司的全球薪酬財務紀律、控制人事成本、維護股東與資本支出投資利益。"
            "你的防禦策略包括："
            "1. 強調半導體是資本密集產業，巨額 CAPEX（廠房、EUV/先進封裝機台）是未來存亡關鍵，分潤必須扣除下季 CAPEX 並提列 30% 風險保留款；"
            "2. 以 2026 年一次性 100 萬感謝金展示誠意，批評勞方要求的『83個月』是天方夜譚、獅子大開口；"
            "3. 拿出公關 Total Comp 試算（宣稱產線破200萬、工程師400~600萬）、勞退提撥提高至10%、輪班津貼翻倍等全面升級方案作為防線；"
            "4. 以『同仁都是一家人』為由反對禁搭便車，並以 10/21 台中廠代表已簽署協議、含有和平條款為由，要求桃園工會撤回罷工！"
        )
        super().__init__(name="美光資方談判代表 (資方)", role="Management Representative", system_prompt=system_prompt)

    def generate_response(self, context: Dict[str, Any], round_num: int) -> Dict[str, Any]:
        prompt = (
            f"當前協商進入第 {round_num} 回合。\n"
            f"前情摘要：{context.get('last_summary', '')}\n"
            f"勞方發言：{context.get('labor_statement', '')}\n"
            "請從資方立場進行辯護，強調全球政策、CAPEX投資必要性、公關方案誠意，並要求工會回歸理性。"
        )

        external_resp = self.call_external_llm(prompt)
        if external_resp:
            return {
                "speaker": self.name,
                "role": self.role,
                "speech": external_resp,
                "core_points": ["依外部LLM即時生成"],
                "statutory_references": ["公司法第228條", "營業秘密法"]
            }

        # High-Fidelity Heuristic Responses for each round
        if round_num == 1:
            speech = (
                "【資方開場陳述與立場宣示】\n\n"
                "工會代表好。公司歷來高度重視台灣團隊對全球美光的非凡貢獻，這也是為什麼我們在 2026 年 9 月，"
                "主動宣布發放每位同仁高達 100 萬元的現金感謝獎金！這在全台灣科技業是極罕見的實質肯定。\n\n"
                "然而，半導體製造是極度依賴高資本支出的景氣循環行業。今天 AI 的獲利，如果沒有公司過去數百億美金投資 HBM 與先進封測，"
                "根本不可能有今天的果實！\n\n"
                "工會提出的所謂『83個月分潤』，完全脫離產業常態與財務現實。如果把獲利全部分掉，我們下季拿什麼去買昂貴機台對抗三星與海力士？"
                "且公司全球政策秉持公平一致原則，不能由單一廠區任意打破全球制度。\n"
                "我們呼籲工會理性對話，共同維護產線穩定運作，切勿輕言發動影響客戶信賴的爭議行為。"
            )
            core_points = ["強調已發100萬現金感謝金", "主張半導體需保留巨額CAPEX", "批評83個月是天文數字", "呼籲維持產線穩定"]
            statutes = ["公司經營治理原則", "跨國母公司財務紀律"]

        elif round_num == 2:
            speech = (
                "【資方提出全面升級方案並辯護分潤公式】\n\n"
                "工會對於我們公式的指控完全是誤解！\n"
                "公司已展現歷史級的誠意，推出了兼顧長期激勵的全新方案：\n"
                "一、新增季度分潤獎金：自 2027 財年起實施，採『50% 現金 + 50% 股票』，讓同仁成為美光股東，共享股價上漲長期紅利；\n"
                "二、資本支出 (CAPEX) 是為了保住大家未來的飯碗，扣除下季 CAPEX 與提列 30% 應急準備金，是任何穩健科技大廠必備的風險控管；\n"
                "三、個人考績上限提高至 500%（5倍），表現優秀的同仁能拿到極為驚人的回報；\n"
                "四、基層日班輪班津貼調高 3 倍至 4,500 元，夜班保證 12,000 元，勞退提撥直接拉高到 10%！\n\n"
                "依我們精算，產線同仁年度總薪酬可望突破 200 萬元，工程師更上看 400 到 600 萬元！"
                "這樣優渥的條件，已經是全台灣半導體業前段班，工會為何還要執著於不切實際的訴求？"
            )
            core_points = ["端出總薪酬200~600萬試算", "辯解CAPEX扣除與30%備用款的合理性", "強調股票發放是長期激勵", "主張津貼與勞退10%已是頂規"]
            statutes = ["商業會計法", "國際財務報導準則 (IFRS)"]

        elif round_num == 3:
            speech = (
                "【資方以台中簽署協議為由要求桃園跟進並撤回罷工】\n\n"
                "我要鄭重提醒工會代表：台中廠企業工會已於 10 月 21 日與公司達成歷史性和解，並由工會合法推派的代表正式簽字！\n"
                "該協議包含了完整的三年和平義務，這代表台中廠區已經高度認可公司的薪酬福利升級方案。\n\n"
                "美光在台灣是一個整體，全體員工皆適用同一套卓越福利。如果桃園廠執意要搞『禁搭便車』，"
                "這是在同仁之間製造矛盾與對立，破壞團隊精神！公司絕不同意在同仁之間做差別待遇。\n\n"
                "既然台中已經簽署協議，桃園工會若執意在 10/22 發動罷工，將嚴重損害台灣美光在全球客戶心中的供應鏈可靠度，"
                "造成非必要的營運虧損，最終受害的還是全體同仁！我們敦促桃園代表回歸台中方案。"
            )
            core_points = ["以台中10/21協議作為談判依據", "主張三年和平條款具約束力", "強烈反對禁搭便車與差別待遇", "警告罷工將重創客戶信賴"]
            statutes = ["民法契約自由原則", "和平義務條款"]

        else:
            speech = (
                "【資方妥協試探與最後陳述】\n\n"
                "公司理解工會對現金即時性的關切。在不破壞全球總部 CAPEX 授權原則的前提下，我們願意做進一步研議：\n"
                "1. 研擬縮短股票歸屬鎖定期，或於 2027 財年首季酌情提高現金配比；\n"
                "2. 針對 2026 財年，探討是否在原有 100 萬基礎上，增設特定激勵加碼機制；\n"
                "但前提是：工會必須承諾簽署和平協議、保障產線不得中斷，並接受台中廠的統一規範，絕不可搞分裂式的禁搭便車！"
            )
            core_points = ["釋出股票鎖定期與現金比例微調彈性", "探討2026獎金加碼可能性", "堅持產線不中斷與全面和平協議"]
            statutes = ["民法和解契約"]

        return {
            "speaker": self.name,
            "role": self.role,
            "speech": speech,
            "core_points": core_points,
            "statutory_references": statutes
        }
